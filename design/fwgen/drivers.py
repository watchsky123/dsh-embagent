"""Generate C driver sources (init + read) for common parts from the register tables.

The code talks to the bus through a small HAL (``tf_hal.h``) that the project provides:
``tf_i2c_write``/``tf_i2c_read``/``tf_delay_ms`` (and the GPIO calls for single-wire parts).
``hal_arduino()`` returns an Arduino ``Wire`` implementation of it.
"""

from __future__ import annotations

import re
from typing import Any

from hw_velxio.design.fwgen.drivers_data import PARTS

HAL_H = """\
/* HAL used by the generated drivers. Implement these for your platform. */
#ifndef TF_HAL_H
#define TF_HAL_H
#include <stddef.h>
#include <stdint.h>
#ifdef __cplusplus
extern "C" {
#endif
/* Return 0 on success, non-zero on a bus error. */
int tf_i2c_write(uint8_t addr, const uint8_t *data, size_t len);
int tf_i2c_read(uint8_t addr, uint8_t *data, size_t len);
void tf_delay_ms(uint32_t ms);
/* Single-wire parts (DHT11) */
void tf_delay_us(uint32_t us);
void tf_pin_output_low(int pin);
void tf_pin_release(int pin);           /* input with pull-up */
int tf_pin_read(int pin);
#ifdef __cplusplus
}
#endif
#endif /* TF_HAL_H */
"""


def hal_arduino() -> str:
    return """\
// Arduino implementation of tf_hal.h (Wire for I2C).
#include <Arduino.h>
#include <Wire.h>
extern "C" {
#include "tf_hal.h"
}
extern "C" int tf_i2c_write(uint8_t addr, const uint8_t *data, size_t len) {
  Wire.beginTransmission(addr);
  Wire.write(data, len);
  return Wire.endTransmission() == 0 ? 0 : 1;
}
extern "C" int tf_i2c_read(uint8_t addr, uint8_t *data, size_t len) {
  if (Wire.requestFrom(addr, (uint8_t)len) != len) return 1;
  for (size_t i = 0; i < len; i++) data[i] = Wire.read();
  return 0;
}
extern "C" void tf_delay_ms(uint32_t ms) { delay(ms); }
extern "C" void tf_delay_us(uint32_t us) { delayMicroseconds(us); }
extern "C" void tf_pin_output_low(int pin) { pinMode(pin, OUTPUT); digitalWrite(pin, LOW); }
extern "C" void tf_pin_release(int pin) { pinMode(pin, INPUT_PULLUP); }
extern "C" int tf_pin_read(int pin) { return digitalRead(pin); }
"""


def supported_parts() -> list[str]:
    return sorted(PARTS)


def _lookup(part: str) -> tuple[str, dict[str, Any]]:
    key = re.sub(r"[^A-Z0-9]", "", part.upper())
    for name, data in PARTS.items():
        if re.sub(r"[^A-Z0-9]", "", name) == key:
            return name, data
    raise KeyError(f"no driver for {part!r} (available: {', '.join(supported_parts())})")


def _hex(value: int, width: int = 2) -> str:
    return f"0x{value:0{width}X}"


def generate_driver(part: str, address: int | None = None) -> dict[str, str]:
    """Return {filename: text} (``<part>.h`` and ``<part>.c``) for a part."""
    name, data = _lookup(part)
    lower = name.lower()
    addr = address if address is not None else data["address"]
    builders = {
        "regs": _regs,
        "cmd": _cmd,
        "oled": _oled,
        "onewire": _onewire,
    }
    header, source = builders[data["kind"]](name, lower, data, addr)
    return {f"{lower}.h": header, f"{lower}.c": source}


def _prologue(name: str, data: dict[str, Any], addr: int | None) -> list[str]:
    # [hwv] 生成的代码里写我们自己的名字，不写上游项目名
    lines = [f"/* {name} driver. Generated by hw_velxio fw-driver. */"]
    lines.append(f"/* Datasheet: {data['datasheet']} */")
    if addr is not None:
        note = data.get("address_note", "")
        lines.append(f"/* I2C address: {_hex(addr)} ({note}) */")
    return lines


def _read_struct(name: str, read: dict[str, Any]) -> list[str]:
    if read.get("raw_bytes"):
        return []
    lines = ["typedef struct {"]
    for ctype, field, _ in read["fields"]:
        lines.append(f"    {ctype} {field};")
    lines.append(f"}} {name.lower()}_{read['name']}_t;")
    return lines


def _read_proto(name: str, read: dict[str, Any]) -> str:
    lower = name.lower()
    if read.get("raw_bytes"):
        return f"int {lower}_read_{read['name']}(uint8_t out[{read['length']}]);"
    return f"int {lower}_read_{read['name']}({lower}_{read['name']}_t *out);"


def _header(
    name: str, data: dict[str, Any], addr: int | None, body: list[str], protos: list[str]
) -> str:
    lower = name.lower()
    guard = f"{name.upper()}_H"
    lines = _prologue(name, data, addr) + [
        f"#ifndef {guard}",
        f"#define {guard}",
        "#include <stdint.h>",
        "",
    ]
    if addr is not None:
        lines.append(f"#define {name.upper()}_ADDR {_hex(addr)}")
    lines += body + [""] + protos + ["", f"#endif /* {guard} */", ""]
    del lower
    return "\n".join(lines)


def _crc_fn() -> list[str]:
    return [
        "/* CRC-8, polynomial 0x31, init 0xFF (datasheet 4.12) */",
        "static uint8_t crc8(const uint8_t *d, int n) {",
        "    uint8_t crc = 0xFF;",
        "    for (int i = 0; i < n; i++) {",
        "        crc ^= d[i];",
        "        for (int b = 0; b < 8; b++) crc = (crc & 0x80) ? (uint8_t)((crc << 1) ^ 0x31) : (uint8_t)(crc << 1);",
        "    }",
        "    return crc;",
        "}",
        "",
    ]


def _regs(name: str, lower: str, data: dict[str, Any], addr: int):
    up = name.upper()
    body = []
    for reg, value, doc in data["registers"]:
        body.append(f"#define {up}_REG_{reg} {_hex(value)} /* {doc} */")
    protos = [f"int {lower}_init(void);"]
    structs = []
    for read in data["reads"]:
        structs += _read_struct(name, read) + [""]
        protos.append(_read_proto(name, read))
    for write in data.get("writes", []):
        protos.append(f"int {lower}_{write['name']}(const uint8_t v[{write['length']}]);")
    header = _header(name, data, addr, body + [""] + structs, protos)

    src = _prologue(name, data, addr) + [f'#include "{lower}.h"', '#include "tf_hal.h"', ""]
    src += [
        "static int write_reg(uint8_t reg, uint8_t value) {",
        "    uint8_t buf[2] = {reg, value};",
        f"    return tf_i2c_write({up}_ADDR, buf, 2);",
        "}",
        "",
        "static int read_regs(uint8_t reg, uint8_t *out, size_t len) {",
        f"    if (tf_i2c_write({up}_ADDR, &reg, 1)) return 1;",
        f"    return tf_i2c_read({up}_ADDR, out, len);",
        "}",
        "",
        f"int {lower}_init(void) {{",
    ]
    if "check" in data:
        reg, expect = data["check"]
        src += [
            "    uint8_t id;",
            f"    if (read_regs({up}_REG_{reg}, &id, 1)) return 1;",
            f"    if (id != {_hex(expect)}) return 2; /* wrong chip id */",
        ]
    for reg, value, doc in data["init"]:
        src.append(f"    if (write_reg({up}_REG_{reg}, {_hex(value)})) return 1; /* {doc} */")
    if data.get("init_delay_ms"):
        src.append(f"    tf_delay_ms({data['init_delay_ms']});")
    src += ["    return 0;", "}", ""]
    for read in data["reads"]:
        start = f"{up}_REG_{read['start']}"
        if read.get("raw_bytes"):
            src += [
                f"/* {read['doc']} */",
                f"int {lower}_read_{read['name']}(uint8_t out[{read['length']}]) {{",
                f"    return read_regs({start}, out, {read['length']});",
                "}",
                "",
            ]
            continue
        src += [
            f"/* {read['doc']} */",
            f"int {lower}_read_{read['name']}({lower}_{read['name']}_t *out) {{",
            f"    uint8_t b[{read['length']}];",
            f"    if (read_regs({start}, b, {read['length']})) return 1;",
        ]
        for _ctype, field, expr in read["fields"]:
            src.append(f"    out->{field} = {expr};")
        src += ["    return 0;", "}", ""]
    for write in data.get("writes", []):
        n = write["length"]
        src += [
            f"/* {write['doc']} */",
            f"int {lower}_{write['name']}(const uint8_t v[{n}]) {{",
            f"    uint8_t buf[{n + 1}];",
            f"    buf[0] = {up}_REG_{write['start']};",
            f"    for (int i = 0; i < {n}; i++) buf[i + 1] = v[i];",
            f"    return tf_i2c_write({up}_ADDR, buf, {n + 1}); /* address auto-increments (SEQOP=0) */",
            "}",
            "",
        ]
    return header, "\n".join(src)


def _cmd(name: str, lower: str, data: dict[str, Any], addr: int):
    up = name.upper()
    cmds = {c[0]: c for c in data["commands"]}
    body = [f"#define {up}_CMD_{c} {_hex(v, 4)} /* {doc} */" for c, v, doc in data["commands"]]
    protos = [f"int {lower}_init(void);"]
    structs = []
    for read in data["reads"]:
        structs += _read_struct(name, read) + [""]
        protos.append(_read_proto(name, read))
    header = _header(name, data, addr, body + [""] + structs, protos)
    src = _prologue(name, data, addr) + [f'#include "{lower}.h"', '#include "tf_hal.h"', ""]
    src += _crc_fn()
    src += [
        "static int send_cmd(uint16_t cmd) {",
        "    uint8_t buf[2] = {(uint8_t)(cmd >> 8), (uint8_t)(cmd & 0xFF)};",
        f"    return tf_i2c_write({up}_ADDR, buf, 2);",
        "}",
        "",
        f"int {lower}_init(void) {{",
    ]
    for cmd, _v, doc in data["init"]:
        assert cmd in cmds
        src.append(f"    if (send_cmd({up}_CMD_{cmd})) return 1; /* {doc} */")
    if data.get("init_delay_ms"):
        src.append(f"    tf_delay_ms({data['init_delay_ms']});")
    src += ["    return 0;", "}", ""]
    for read in data["reads"]:
        n = read["length"]
        src += [
            f"/* {read['doc']} */",
            f"int {lower}_read_{read['name']}({lower}_{read['name']}_t *out) {{",
            f"    uint8_t b[{n}];",
            f"    if (send_cmd({up}_CMD_{read['command']})) return 1;",
            f"    tf_delay_ms({read['delay_ms']});",
            f"    if (tf_i2c_read({up}_ADDR, b, {n})) return 1;",
        ]
        for first, _second, crc in read.get("crc", []):
            src.append(f"    if (crc8(&b[{first}], 2) != b[{crc}]) return 3; /* CRC error */")
        for _ctype, field, expr in read["fields"]:
            src.append(f"    out->{field} = {expr};")
        src += ["    return 0;", "}", ""]
    return header, "\n".join(src)


def _oled(name: str, lower: str, data: dict[str, Any], addr: int):
    up = name.upper()
    w, h = data["width"], data["height"]
    ctl = data["control"]
    body = [
        f"#define {up}_WIDTH {w}",
        f"#define {up}_HEIGHT {h}",
        f"#define {up}_CTRL_CMD {_hex(ctl['command'])} /* Co=0 D/C#=0 */",
        f"#define {up}_CTRL_DATA {_hex(ctl['data'])} /* Co=0 D/C#=1 */",
    ]
    protos = [
        f"int {lower}_init(void);",
        f"/* Write a full framebuffer of {w * h // 8} bytes (page-major, 1 bit per pixel). */",
        f"int {lower}_write_frame(const uint8_t fb[{w * h // 8}]);",
    ]
    header = _header(name, data, addr, body, protos)
    src = _prologue(name, data, addr) + [f'#include "{lower}.h"', '#include "tf_hal.h"', ""]
    src += [
        "static int cmd(uint8_t c) {",
        f"    uint8_t buf[2] = {{{up}_CTRL_CMD, c}};",
        f"    return tf_i2c_write({up}_ADDR, buf, 2);",
        "}",
        "",
        f"int {lower}_init(void) {{",
        "    tf_delay_ms(100); /* power-up (datasheet 8.9) */",
    ]
    for opcode, params, doc in data["init"]:
        src.append(f"    if (cmd({_hex(opcode)})) return 1; /* {doc} */")
        for p in params:
            src.append(f"    if (cmd({_hex(p)})) return 1;")
    src += ["    return 0;", "}", ""]
    src += [
        f"int {lower}_write_frame(const uint8_t fb[{w * h // 8}]) {{",
        "    if (cmd(0x21) || cmd(0) || cmd(" + str(w - 1) + ")) return 1; /* column range */",
        "    if (cmd(0x22) || cmd(0) || cmd(" + str(h // 8 - 1) + ")) return 1; /* page range */",
        "    for (int i = 0; i < " + str(w * h // 8) + "; i += 16) {",
        f"        uint8_t buf[17] = {{{up}_CTRL_DATA}};",
        "        for (int j = 0; j < 16; j++) buf[j + 1] = fb[i + j];",
        f"        if (tf_i2c_write({up}_ADDR, buf, 17)) return 1;",
        "    }",
        "    return 0;",
        "}",
        "",
    ]
    return header, "\n".join(src)


def _onewire(name: str, lower: str, data: dict[str, Any], addr: None):
    up = name.upper()
    body = [
        "typedef struct {",
        "    float temperature_c;",
        "    float humidity_pct;",
        f"}} {lower}_reading_t;",
    ]
    protos = [
        "/* pin: the data pin number used by tf_pin_* in tf_hal.h. Returns 0, 1 = no response,",
        "   2 = timeout, 3 = checksum error. Call at most once per second. */",
        f"int {lower}_read(int pin, {lower}_reading_t *out);",
    ]
    header = _header(name, data, None, body, protos)
    src = _prologue(name, data, None) + [f'#include "{lower}.h"', '#include "tf_hal.h"', ""]
    src += [
        f"#define {up}_START_LOW_MS {data['start_low_ms']}",
        f"#define {up}_BIT_THRESHOLD_US {data['bit_threshold_us']}",
        "",
        "/* wait until the pin equals level; return the time waited in us or -1 */",
        "static int wait_level(int pin, int level, int max_us) {",
        "    for (int t = 0; t < max_us; t++) {",
        "        if (tf_pin_read(pin) == level) return t;",
        "        tf_delay_us(1);",
        "    }",
        "    return -1;",
        "}",
        "",
        f"int {lower}_read(int pin, {lower}_reading_t *out) {{",
        "    uint8_t d[5] = {0, 0, 0, 0, 0};",
        "    tf_pin_output_low(pin);",
        f"    tf_delay_ms({up}_START_LOW_MS);",
        "    tf_pin_release(pin);",
        "    tf_delay_us(30);",
        "    if (wait_level(pin, 0, 100) < 0) return 1;  /* response low 80 us */",
        "    if (wait_level(pin, 1, 120) < 0) return 2;  /* response high 80 us */",
        "    if (wait_level(pin, 0, 120) < 0) return 2;",
        "    for (int i = 0; i < 40; i++) {",
        "        if (wait_level(pin, 1, 80) < 0) return 2; /* 50 us low gap */",
        "        int high = wait_level(pin, 0, 120);       /* 26-28 us = 0, 70 us = 1 */",
        "        if (high < 0) return 2;",
        f"        d[i / 8] = (uint8_t)((d[i / 8] << 1) | (high > {up}_BIT_THRESHOLD_US ? 1 : 0));",
        "    }",
        "    if ((uint8_t)(d[0] + d[1] + d[2] + d[3]) != d[4]) return 3;",
        "    out->humidity_pct = (float)d[0] + (float)d[1] / 10.0f;",
        "    out->temperature_c = (float)d[2] + (float)d[3] / 10.0f;",
        "    return 0;",
        "}",
        "",
    ]
    return header, "\n".join(src)
